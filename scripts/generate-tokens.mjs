import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(
  readFileSync(
    new URL("../src/design-system/tokens.json", import.meta.url),
    "utf8",
  ),
);
const lines = [];
const property = (name, value) =>
  lines.push(`  --${name.replaceAll("/", "-")}: ${value};`);
for (const [name, value] of Object.entries(tokens.primitives))
  property(`primitive-${name}`, value);
for (const [name, value] of Object.entries(tokens.colors))
  property(`color-${name}`, `var(--primitive-${value.replaceAll("/", "-")})`);
for (const group of ["spacing", "radius"])
  for (const [name, value] of Object.entries(tokens[group]))
    property(`${group === "spacing" ? "space" : group}-${name}`, `${value}px`);
for (const [name, value] of Object.entries(tokens.typography)) {
  property(`type-${name}-size`, `${value.size}px`);
  property(`type-${name}-line`, `${value.lineHeight}px`);
}
writeFileSync(
  new URL("../src/design-system/tokens.css", import.meta.url),
  `/* Generated by npm run tokens. Edit tokens.json. */\n:root {\n${lines.join("\n")}\n}\n`,
);
